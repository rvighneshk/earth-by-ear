// The tour of a single picture (GEOS Aerosols-style): finds a low, a busy and a high place, all different, with honest captions.
import fs from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';
const here = path.dirname(fileURLToPath(import.meta.url));
const T = await import(path.join(here, '../app/static/js/tour.js'));
const base = path.join(here, '../app/static/data/');
const idx = JSON.parse(fs.readFileSync(base + 'index.json')).datasets;
const ds = idx.find((d) => d.id === 'eic-geos-aerosols') ?? idx[0];
const j = JSON.parse(fs.readFileSync(base + ds.frames[0].url));
const g = { rows: j.rows, cols: j.cols, extent: ds.extent, geometry: ds.geometry, data: Float32Array.from(j.data, (v) => (v === null ? NaN : v)) };
const stops = T.findStillStops(g, ds);
if (stops.length < 2) throw new Error('expected at least two stops, got ' + stops.length);
const places = new Set(stops.map((s) => `${s.r},${s.c}`));
if (places.size !== stops.length) throw new Error('stops must be at different places');
const hi = stops.find((s) => s.kind === 'high'); const lo = stops.find((s) => s.kind === 'low');
if (!hi || !lo) throw new Error('missing high/low stop');
const v = (s) => g.data[s.r * g.cols + s.c];
if (!(v(hi) > v(lo))) throw new Error('high stop must be higher than low stop');
for (const s of stops) if (!s.text.includes(s.where)) throw new Error('caption must name its place');
console.log(`still tour ok on ${ds.id}: ` + stops.map((s) => `${s.kind}@${s.r},${s.c}=${v(s).toFixed(0)}`).join('  '));
console.log('  e.g.', stops[0].text);
console.log('  intro:', T.tourIntroStill(ds, stops));
